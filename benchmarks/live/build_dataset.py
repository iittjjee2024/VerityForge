"""Builds the live-evaluation dataset with GROUND TRUTH taken from the endoflife.date API, fetched at build time.

Gold is independent of Tavily, Bifrost and our pipeline. Claims are generated by fixed templates (not hand-picked),
per product:
  1. "<Name> <cycle> is still supported."   cycle = a currently supported (non-newest) release  -> gold TRUE
  2. "<Name> <cycle> is still supported."   cycle = a release that went EOL > 1 year ago        -> gold FALSE
  3. "The latest stable release of <Name> is <cycle>."  alternates TRUE (newest released cycle) / FALSE (an older one)
plus 2 stable control claims per set (expected: Not Time-Sensitive, no search).

Sets: DEV products are used while fixing the pipeline; HELDOUT products are evaluated once afterwards.
Usage: python benchmarks/live/build_dataset.py
"""
import json
from datetime import date, datetime, timezone
from pathlib import Path

import httpx

SETS = {
    "dev": [("python", "Python"), ("nodejs", "Node.js"), ("postgresql", "PostgreSQL"), ("django", "Django")],
    "heldout": [("php", "PHP"), ("ruby", "Ruby"), ("go", "Go"), ("ubuntu", "Ubuntu")],
}
CONTROLS = {
    "dev": ["Water boils at 100 degrees Celsius at sea level.",
            "The speed of light in a vacuum is about 299,792 kilometres per second."],
    "heldout": ["Paris is the capital city of France.", "A triangle has three sides and three angles."],
}
TODAY = datetime.now(timezone.utc).date()


def eol_date(row):
    e = row.get("eol")
    if e is False:
        return None            # no EOL announced -> supported
    if e is True:
        return date(1970, 1, 1)  # EOL with unknown date -> already ended
    return date.fromisoformat(e)


def released(row):
    return date.fromisoformat(row["releaseDate"]) <= TODAY if row.get("releaseDate") else False


def supported(row) -> bool:
    e = eol_date(row)
    return released(row) and (e is None or e > TODAY)


def build_set(name: str) -> list[dict]:
    items = []
    for slug, label in SETS[name]:
        r = httpx.get(f"https://endoflife.date/api/{slug}.json", timeout=30, follow_redirects=True)
        r.raise_for_status()
        rows = [x for x in r.json() if released(x)]           # newest first
        newest = rows[0]
        sup = [x for x in rows[1:] if supported(x)]
        old = [x for x in rows if (eol_date(x) or TODAY) < date(TODAY.year - 1, TODAY.month, TODAY.day)]
        pick = lambda x: {"cycle": x["cycle"], "releaseDate": x.get("releaseDate"), "eol": x.get("eol")}  # noqa: E731
        if sup:
            x = sup[len(sup) // 2]  # middle of the supported range, not the newest
            items.append({"id": f"{slug}-supported-true", "product": label, "kind": "supported", "gold": "true",
                          "claim": f"{label} {x['cycle']} is still supported.", "evidence": pick(x)})
        if old:
            x = old[0]  # most recent release that ended more than a year ago
            items.append({"id": f"{slug}-supported-false", "product": label, "kind": "supported", "gold": "false",
                          "claim": f"{label} {x['cycle']} is still supported.", "evidence": pick(x)})
        true_latest = len(items) % 2 == 0
        x = newest if true_latest else rows[min(2, len(rows) - 1)]
        items.append({"id": f"{slug}-latest-{'true' if true_latest else 'false'}", "product": label,
                      "kind": "latest", "gold": "true" if true_latest else "false",
                      "claim": f"The latest stable release of {label} is {x['cycle']}.",
                      "evidence": {"newest_cycle": newest["cycle"], **pick(x)}})
    for i, c in enumerate(CONTROLS[name]):
        items.append({"id": f"control-{i}", "product": "-", "kind": "control", "gold": "stable", "claim": c,
                      "evidence": {}})
    return items


if __name__ == "__main__":
    out = {"source": "https://endoflife.date/api/<product>.json", "fetched_on": TODAY.isoformat(),
           "note": "Gold derived from the API on fetched_on. Gold 'true' means the claim is correct that day.",
           "sets": {k: build_set(k) for k in SETS}}
    path = Path(__file__).with_name("dataset.json")
    path.write_text(json.dumps(out, indent=2), "utf-8")
    for k, v in out["sets"].items():
        print(f"[{k}] {len(v)} claims")
        for it in v:
            print(f"   {it['gold']:>6}  {it['claim']}")
